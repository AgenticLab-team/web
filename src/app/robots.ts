import type { MetadataRoute } from "next";

import { PROTECTED_PREFIXES } from "@/lib/auth/routes";
import { env } from "@/lib/env";

/**
 * robots.txt。
 *
 * ─────────────────────────────────────────
 * 之前站里根本没有这个文件
 * ─────────────────────────────────────────
 *
 * `/robots.txt` 返回 200，于是看起来一切正常 —— 但那是
 * **Cloudflare 塞进来的默认内容**。这个站对爬虫说什么，
 * 一直是由别人替它决定的。
 *
 * ─────────────────────────────────────────
 * 两类，理由完全不同
 * ─────────────────────────────────────────
 *
 * **① 要登录的** —— 直接从 `PROTECTED_PREFIXES` 生成。
 *
 * 这些路径本来就有门禁，爬虫拿到的只有 307。写在这里不是为了拦人，
 * 是为了别让搜索引擎把配额花在一堆登录跳转上 ——
 * 那会让真正该被收录的帖子排在后面。
 *
 * **手抄一份是不行的**：那张名单会变（论坛那道门就刚加过），
 * 而抄件不会跟着变。漏的方向还特别难发现 ——
 * robots.txt 少一条，没有任何东西会报错。
 *
 * **② 能看但不该被搜到的** —— 下面那张小表，每条写清为什么。
 */

/**
 * 公开可见、但**不希望被检索**的路径。
 *
 * 这一档和上面那张名单的区别是要紧的：那些是「不该被看到」，
 * 这些是**「能看到，但不该用名字搜出来」**。
 */
const PUBLIC_BUT_NOT_INDEXED: readonly { path: string; why: string }[] = [
  {
    path: "/leaderboard",
    why:
      "「未登录访客还是可以看见大榜单的」是定下来的规矩，这一条不动。" +
      "但「打开链接看得到」和「用名字能在谷歌里搜出来」是两件事：" +
      "后者意味着一个人的微信昵称、头像和发言量会绑在他的名字上、" +
      "被任何一个搜他的人看到 —— 而他当初只是加了个微信群。" +
      "隐私页自己写着，把发言量做成对访客公开的榜单是微信里不存在的暴露；" +
      "让它可被检索，是在那个暴露之外再加一层",
  },
  {
    path: "/login",
    why: "收录一个登录页没有意义，还会在搜索结果里挤掉真正的内容",
  },
  {
    path: "/p/",
    why:
      "分享短链是 302 到帖子本身，收录它等于同一篇帖子有两个地址 —— " +
      "而且短链是发给特定的人的，不该反过来变成一条可被检索的线索",
  },
];

/** 只给测试和文档用 —— 每条「能看但不收录」都得写得出为什么 */
export const NOT_INDEXED_REASONS = PUBLIC_BUT_NOT_INDEXED;

export default function robots(): MetadataRoute.Robots {
  /*
   * robots.txt 的匹配是**纯前缀**的，不是路径段匹配。
   *
   * 所以 `/me` 这一条已经盖住了 `/me/profile`，
   * 再写一条 `/me/` 是纯冗余 —— 第一版两条都发了，
   * 产物里 12 条变成了 24 条，读的人会以为这里有什么讲究。
   *
   * 反过来也要知道代价：`/me` 同样盖住了 `/members`。
   * 这里恰好无所谓（`/members` 本来就在名单里），
   * 但**将来加一条公开路径时要留意别撞上某个前缀**。
   */
  const disallow = [
    // 接口不是给人看的，也不该出现在搜索结果里
    "/api/",
    ...PROTECTED_PREFIXES,
    ...PUBLIC_BUT_NOT_INDEXED.map((entry) => entry.path),
  ];

  return {
    rules: [{ userAgent: "*", allow: "/", disallow }],
    sitemap: `${env.site.url}/sitemap.xml`,
    host: env.site.url,
  };
}
