import Link from "next/link";

import { Empty, EmptyAction } from "@/components/ui/primitives";
import { PageHeader } from "@/components/shell/PageHeader";

/**
 * 帖子找不到时的那一屏。
 *
 * ─────────────────────────────────────────
 * 「不存在」和「你看不了」故意长得一模一样
 * ─────────────────────────────────────────
 *
 * 帖子页对这两种情况给的都是 `notFound()`（见 page.tsx），
 * 因为 403 等于告诉对方「这个帖子存在，只是你看不了」——
 * 对私密内容来说，**存在性本身就是信息**。
 *
 * 所以这一页的文案也必须两种都盖得住：不能写「这个帖子已被删除」
 * （那等于承认它存在过），也不能写「你没有权限」（同样泄露）。
 * 「不在这里」是唯一两种都成立的说法。
 *
 * ─────────────────────────────────────────
 * 为什么值得单独写一页
 * ─────────────────────────────────────────
 *
 * 根目录那个 404 是给「地址敲错了」准备的。而点进一个失效帖子链接的人
 * 处境完全不同：他多半是从微信里点进来的，手里有一条别人分享的链接，
 * 他需要知道的是「要不要回去问一句」——
 * 而不是被请去首页看社区脉搏。
 *
 * ─────────────────────────────────────────
 * 状态码是 200，这是已知且刻意接受的
 * ─────────────────────────────────────────
 *
 * 这一段路由有 `loading.tsx`，响应在 `notFound()` 执行前就已经开始
 * 流式发送，**状态码此后改不了**（Next 文档 loading#status-codes 写明了）。
 *
 * 文档给的另一条路是「在 proxy 里先查一次」—— 这里**故意不走**：
 * proxy 只能查「这条 id 存不存在」，查不了可见性。那样一来
 * 不存在的帖子返回 404、存在但看不见的返回 200，
 * 两者一比就把「这个帖子存在」泄露了 —— 正是上面那条规矩要挡的。
 *
 * 软 404 的代价由 Next 自己兜住：它给 not-found 输出加了
 * `<meta name="robots" content="noindex">`，搜索引擎不会收录。
 * 线上实测确认过这个 meta 确实在。
 */
export default function PostNotFound() {
  return (
    <>
      <PageHeader title="帖子" />
      <Empty
        title="这个帖子不在这里"
        hint="它可能已经被删掉了，也可能只对特定成员开放 —— 从这里看不出是哪一种，这是故意的。"
        action={<EmptyAction href="/forum">回论坛看看</EmptyAction>}
      />
      <p className="t-caption mt-4 px-1 text-center text-[var(--ink-tertiary)]">
        链接是别人分享给你的？
        <Link href="/search" className="text-[var(--accent)]">
          搜一下关键词
        </Link>
        ，公开的内容多半还在。
      </p>
    </>
  );
}
