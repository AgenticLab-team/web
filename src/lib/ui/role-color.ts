/**
 * 角色徽章的颜色。
 *
 * ═════════════════════════════════════════
 * 库里那一列颜色是**按浅色底挑的**
 * ═════════════════════════════════════════
 *
 * `roles.color` 存的是一组固定的十六进制值（`#0F172A`、`#B45309`…），
 * 挑的时候看的是白底。而这个站有深浅两套配色，那一列不跟着变 ——
 * 于是深色下整排角色徽章一起失效：
 *
 *     成员   #0F172A → 对比度 1.04   （浅色下 17.85）
 *     封禁   #7F1D1D → 1.85
 *     审计员 #6D28D9 → 2.61
 *     版主   #1D4ED8 → 2.77
 *     管理员 #B91C1C → 2.87
 *     群管理 3.38 · 站长 3.69 · 外部用户 3.90
 *
 * 「成员」那条尤其糟：**它是绝大多数人自己的徽章**，
 * 而它出现在个人主页上 —— 最常见的那个人、最常看的那一页，
 * 深色下那两个字就是不见了（1.04 等于底色）。
 *
 * 反过来「访客」`#94A3B8` 在**浅色**下只有 2.56 —— 同一组色板，
 * 两边各有各的瞎眼处。
 *
 * ─────────────────────────────────────────
 * 修法：让字色**掺进当前的前景色**
 * ─────────────────────────────────────────
 *
 * `color-mix(in srgb, 角色色 50%, var(--ink))`：
 * 浅色下 `--ink` 是近黑，深色下是近白 —— 同一个表达式，
 * 两边自动往看得清的方向走，而且保住一半的色相（红还是红、蓝还是蓝）。
 *
 * 50% 这个数是算出来的，不是拍的：九个角色 × 两套配色，
 * 最差一格是 4.97（成员 / 深色），刚好过 4.5 那条线。
 * 60% 的话最差掉到 3.65，不够。
 *
 * ⚠️ 只用在**从库里取出来的角色色**上。
 * `var(--danger)` 那类主题变量本来就跟着配色走，再掺一次只会发灰。
 */

/** 徽章的字色 —— 掺一半前景色，两套配色下都够 4.5 */
export function roleInk(color?: string | null): string {
  if (!color) return "var(--ink-secondary)";
  return `color-mix(in srgb, ${color} 50%, var(--ink))`;
}

/** 徽章的底色 —— 同一个色相的一层薄底，不参与对比度 */
export function roleTint(color?: string | null): string {
  if (!color) return "var(--fill)";
  return `color-mix(in srgb, ${color} 14%, transparent)`;
}
