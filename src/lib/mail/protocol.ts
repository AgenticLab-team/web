/**
 * 网关 ↔ 站点之间的线上协议。纯定义，两边共用一份说明。
 *
 * ═════════════════════════════════════════
 * 为什么要有版本号
 * ═════════════════════════════════════════
 *
 * 网关和站点是**两个独立部署的东西**。今天它们可能在同一台机器上，
 * 明天网关搬到别的机房、甚至变成好几台 —— 那时候
 * **它们的版本必然会不一致**：站点先部署了，网关还是上周那份。
 *
 * 没有版本号的话，字段改名的表现是「有些信收不到、有些能收到」，
 * 而两边的日志都显示一切正常。加一个数字之后，
 * 不匹配是一句明确的错误，而不是一个要查三天的怪现象。
 *
 * ─────────────────────────────────────────
 * 改这个数字的规矩
 * ─────────────────────────────────────────
 *
 * **加字段不用动它**（老网关不发新字段，站点当它是 undefined）。
 * 只有**改名、删字段、改语义**才 +1 —— 也就是那些
 * 老网关发过来会被误解的改动。
 */
export const MAIL_PROTOCOL_VERSION = 1;

/**
 * 站点能接受的最老版本。
 *
 * 留一格向后兼容：滚动升级时总有一小段时间新旧网关并存，
 * 而那一段时间里**不能丢信**。
 */
export const MAIL_PROTOCOL_MIN = 1;

export function protocolAcceptable(version: unknown): boolean {
  /*
   * 没带版本号的当 1 —— 第一版网关就是这么发的。
   *
   * 判成不兼容的话，升级站点的那一刻所有还没升级的网关全部失效，
   * 而它们手上正压着信。
   */
  if (version === undefined || version === null) return true;
  /*
   * 必须先判类型，不能直接 `Number(version)`。
   *
   * `Number(true)` 是 **1** —— 也就是说一个 `"protocol": true`
   * 会被当成合法的第一版通过。JSON 是外面送进来的，
   * 而这一层的全部意义就是不相信外面送进来的东西。
   */
  if (typeof version !== "number") return false;
  return (
    Number.isInteger(version) &&
    version >= MAIL_PROTOCOL_MIN &&
    version <= MAIL_PROTOCOL_VERSION
  );
}
