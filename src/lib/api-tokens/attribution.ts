import { SITE_HOST } from "./rules";

/**
 * 把代发署名从消息正文里认出来。
 *
 * ═════════════════════════════════════════
 * 为什么这件事必须做
 * ═════════════════════════════════════════
 *
 * 代发的消息在微信里是**机器人账号发出去的**，所以同步回来之后，
 * 它在库里的作者是机器人，正文最后多一行：
 *
 *   本消息由「张三」使用 AgenticLab.sh 代发
 *
 * 不处理的话有两个后果，都不小：
 *
 *   ① **站内到处都把它显示成一行普通文字**。它和正文同一个字号、
 *      同一个颜色，看起来像发消息的人自己打的一句话 —— 而它是系统加的。
 *   ② **统计全算在机器人头上**。发言榜、活跃度、词频里，
 *      三十条代发消息会让机器人爬到榜首，而真正说话的那三个人
 *      一条都不算 —— 这个站的榜单是它最核心的东西之一。
 *
 * ═════════════════════════════════════════
 * 它和 `withAttribution` 是**一对**，必须一起改
 * ═════════════════════════════════════════
 *
 * 拼的那一头在 rules.ts。这里是解的那一头。
 * 两边对不上的时候不会有任何报错 —— 只是从某一天起，
 * 新发的消息不再被认出来，而旧的还认得出，于是统计里
 * 悄悄混进一批算错的数据。
 *
 * 所以有一条测试**拿 withAttribution 的产出直接喂给这里**，
 * 而不是各自比对一个写死的字符串。
 */

export interface Attributed {
  /** 去掉署名之后的正文 */
  body: string;
  /** 署名里那个人的名字。拼的时候名字为空会写成「某位成员」 */
  senderName: string;
}

/*
 * 名字里什么都可能有（括号、竖线、emoji），所以用非贪婪匹配一直吃到
 * 最后一个 `」`，而不是 `[^」]*` —— 有人的昵称里就带着「」。
 *
 * 锚在结尾（`$`）：署名永远是最后一行。不锚的话，一条**正文里引用了
 * 别人代发消息**的消息会被误判成代发。
 */
const PATTERN = new RegExp(
  `\\n本消息由「(.+)」使用 ${SITE_HOST.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")} 代发$`,
);

/**
 * 认不出来就返回 null —— 绝大多数消息都不是代发的，
 * 所以调用方拿到 null 是常态，不是错误。
 */
export function parseAttribution(content: string): Attributed | null {
  const match = PATTERN.exec(content);
  if (!match) return null;
  return {
    body: content.slice(0, match.index),
    senderName: match[1],
  };
}

