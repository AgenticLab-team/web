import type { ScopeKey } from "./rules";

/**
 * 端点目录的类型。
 *
 * ─────────────────────────────────────────
 * 为什么从 `catalog.ts` 里拆出来
 * ─────────────────────────────────────────
 *
 * 目录本身按域拆成了几份（`catalog-me.ts`、`catalog-forum.ts`……），
 * 而它们都要这个类型。类型留在 `catalog.ts` 里的话，
 * 每一份都要反过来 import 那个聚合文件 —— 一圈循环依赖，
 * 而循环依赖在这里的表现是**某几份的常量初始化成 undefined**，
 * 不是一句报错。
 */

export interface Endpoint {
  method: "GET" | "POST" | "PATCH" | "DELETE";
  path: string;
  summary: string;
  /** 要哪些 scope 才调得动；空数组 = 任何有效令牌都行 */
  scopes: ScopeKey[];
  /** 一句能直接抄去跑的例子 */
  example: string;
  /** 额外要注意的事，会原样显示在文档上 */
  note?: string;
  /**
   * 在线测试里预填的请求体。
   *
   * ─────────────────────────────────────────
   * 没有它，写操作那几条在控制台里等于用不了
   * ─────────────────────────────────────────
   *
   * 控制台原来给所有 POST 都填 `{"text":"…"}` —— 对发消息是对的，
   * 对发帖是错的（要 board / title / content），而人点下去拿到的是
   * 一句 400。他多半会以为是自己令牌不对，而不是这个框里的内容不对。
   *
   * 每条自己带一份能直接按下去的例子，这个问题就不存在了。
   */
  sampleBody?: Record<string, unknown>;
  /**
   * 不需要令牌就能调的那几条。
   *
   * ═════════════════════════════════════════
   * 它必须是个显式字段，不能靠「scopes 为空」推
   * ═════════════════════════════════════════
   *
   * `scopes: []` 现在的含义是「任何**有效令牌**都行」——
   * `/api/v1/docs` 就是这样：它要回答的正是「我这把能干什么」。
   *
   * 如果再让空数组同时表示「不用令牌」，这两件完全不同的事
   * 就没有办法在文档上区分开 —— 而它们的区别恰恰是
   * 「这个接口有没有把门」。
   */
  auth?: "none";
}
