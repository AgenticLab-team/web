import "server-only";

import { nekobot } from "@/lib/nekobot/client";

/**
 * 机器人自己是谁。
 *
 * ═════════════════════════════════════════
 * 统计里必须认得出它
 * ═════════════════════════════════════════
 *
 * 群猫娘在 `daily_stats` 里有一千五百多条消息，按现在的算法
 * 它在总榜上排第 6 —— **和真人同台竞争**。而代发一旦跑通，
 * 每条代发消息都记在它头上，它只会越爬越高。
 *
 * ─────────────────────────────────────────
 * 为什么不能靠 `messages.is_send`
 * ─────────────────────────────────────────
 *
 * 那一列**本来就是干这个的**：采集那侧的注释写着「机器人自己的消息
 * 不进榜也不计分」，聚合的 SQL 里也确实带着 `is_send = 0`。
 *
 * 但线上实测：全站 `is_send = 1` 的行数是 **0**，包括机器人自己
 * 那 1598 条；上游返回的 `is_send` 一律是 false。
 *
 * 也就是说那道过滤一直存在、一直在跑、而且**一直什么都没挡住** ——
 * 一条读起来完全正确的 SQL，配一列永远为假的数据。这种坏法不报错，
 * 只会让下一个人以为已经处理过了（我就差点以为）。
 *
 * 所以改成按 wx_id 认。`is_send = 0` 保留着 —— 哪天上游开始正确填它，
 * 两道闸一起生效，没有坏处。
 *
 * ─────────────────────────────────────────
 * 不存进 settings
 * ─────────────────────────────────────────
 *
 * 存进去它就会出现在后台那一页的旋钮列表里，而它**不是一个旋钮**，
 * 是一条同步下来的事实 —— 管理员手一滑改错，榜单会静悄悄地
 * 把一个真人抹掉。
 *
 * 所以在同步开始时问一次上游，然后把结果一路传下去。
 * 进程内缓存一小时，因为一轮同步里会用到很多次。
 */

/** 缓存多久。机器人的身份基本不变，一小时足够，也够快地跟上换号 */
const TTL_MS = 60 * 60 * 1000;

let cached: { wxId: string | null; at: number } | null = null;

/**
 * 问上游「你是谁」。
 *
 * 取不到时返回 null，**不猜** —— 猜错的后果是把一个真人从榜上抹掉，
 * 比机器人在榜上多待一天严重得多。
 *
 * 失败不抛：取不到身份不该让整轮同步失败。
 */
export async function resolveBotWxId(now = Date.now()): Promise<string | null> {
  if (cached && now - cached.at < TTL_MS) return cached.wxId;

  try {
    const binding = await nekobot.binding();
    const wxId = binding?.bot?.wx_id?.trim() || null;
    cached = { wxId, at: now };
    return wxId;
  } catch {
    /*
     * 上游不通时沿用上一次拿到的值（哪怕已经过期）——
     * 一次网络抖动不该让机器人重新爬上榜单。
     */
    return cached?.wxId ?? null;
  }
}

