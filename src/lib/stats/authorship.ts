/**
 * 一条消息的发言**算在谁头上**。
 *
 * ═════════════════════════════════════════
 * 「谁发的」和「谁说的」不是一回事
 * ═════════════════════════════════════════
 *
 * 绝大多数消息里这两个是同一个人，所以这个概念一直不需要存在。
 * 代发把它们拆开了：
 *
 *   · **发的**是机器人账号（微信层面确实是它发出去的）
 *   · **说的**是那个被授权的成员
 *
 * 榜单要算的是后者。算成前者的话，一个人替群里发了三十条通知，
 * 榜首会是机器人，而他自己一条都不算 —— 两头都错。
 *
 * ─────────────────────────────────────────
 * 机器人自己说的话：一条都不算
 * ─────────────────────────────────────────
 *
 * 它不是成员。它在榜上排第 6 这件事本身就说不通，
 * 而榜单是这个站最核心的东西之一。
 *
 * 返回 `null` 表示「这条不计入任何人」。
 *
 * ─────────────────────────────────────────
 * 为什么是纯函数
 * ─────────────────────────────────────────
 *
 * 这条口径要在**两个地方**成立：采集时决定重算哪些「人 × 天」，
 * 以及重算时决定哪些消息算数。两边各写一份的话会分叉，
 * 而分叉的表现是「榜单数字对不上，但没有任何地方报错」——
 * 这个仓库已经因为 daily_stats 和 messages 对不上吃过一次亏了。
 */

export interface AuthorshipInput {
  /** 微信层面真正发出去的那个账号 */
  senderWxId: string;
  /** 代发时那个成员的 wx_id；不是代发就是 null */
  onBehalfOfWxId?: string | null;
  /** 机器人自己的 wx_id。取不到时传 null —— 那就什么都不排除 */
  botWxId: string | null;
}

/**
 * 这条消息算谁的。null = 不算任何人。
 */
export function creditedWxId(input: AuthorshipInput): string | null {
  /*
   * 代发优先。
   *
   * 顺序很重要：代发消息的 sender 就是机器人，先判机器人的话
   * 它会被整条丢掉 —— 而那正是我们要救回来的那些。
   */
  if (input.onBehalfOfWxId) return input.onBehalfOfWxId;

  // 机器人自己说的话不算任何人
  if (input.botWxId && input.senderWxId === input.botWxId) return null;

  return input.senderWxId;
}
