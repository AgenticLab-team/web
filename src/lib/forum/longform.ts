/**
 * 「这是一篇要坐下来读的东西吗」。
 *
 * ═════════════════════════════════════════
 * 为什么需要这个概念
 * ═════════════════════════════════════════
 *
 * 上线头一批 93 篇帖子量出来的：
 *
 *   长文（≥2000 字）  43 篇，平均 2.3 次浏览、0.21 条回复
 *   短帖（<300 字）   36 篇，平均 8.2 次浏览、1.28 条回复
 *
 * 一条四个字的水帖拿到的注意力是一篇一万字文章的三倍半，
 * 而且 43 篇长文里 33 篇出自同一个人。
 *
 * 原因不在人，在排序：论坛首页是一条按时间刷的流，
 * 于是「所以开水是什么」和一篇讲 MoE 通信墙的一万字并排站着，
 * 一小时后两个一起被冲走 —— 一个花了四秒写，一个花了一天。
 *
 * 所以要有一条**结构上认得出长文**的路。这个文件就是那条路的起点：
 * 它只回答「多长算长」和「读完要多久」，不碰数据库，不碰排版。
 */

/**
 * 多少字算长文。
 *
 * 2000 是数出来的，不是拍的：现有帖子的长度分布在 300 和 2000
 * 之间几乎是空的 —— 要么是几十字的一句话，要么是几千字的成篇文章。
 * 门槛落在空档里，两边都不会误判。
 */
export const LONGFORM_CHARS = 2000;

/**
 * 每分钟读多少字。
 *
 * 中文默认阅读速度通常按 300–500 字/分钟算，这里取偏慢的一端 ——
 * 这些帖子是技术文章，不是小说，而**把时间说短了比说长了糟**：
 * 说「3 分钟」结果读了 15 分钟，下次他就不信这个数了。
 */
const CHARS_PER_MINUTE = 300;

export function isLongform(charCount: number): boolean {
  return charCount >= LONGFORM_CHARS;
}

/**
 * 读完大概要几分钟。至少 1 —— 「0 分钟读完」不是一个说法。
 */
export function readingMinutes(charCount: number): number {
  return Math.max(1, Math.round(charCount / CHARS_PER_MINUTE));
}

/**
 * 给人看的那句话。
 *
 * 超过一小时就不再报分钟数了：「87 分钟」这种精度是假的
 * （谁也不会正好读 87 分钟），而且它传达的信息其实是
 * 「这篇很长，你可能要分两次读」—— 那句话直接说更有用。
 */
export function readingLabel(charCount: number): string {
  const minutes = readingMinutes(charCount);
  if (minutes >= 60) return "一小时以上";
  return `${minutes} 分钟`;
}

/**
 * 正文有多少字。
 *
 * ─────────────────────────────────────────
 * 按**码点**数，不是 `.length`
 * ─────────────────────────────────────────
 *
 * `"🧠".length` 是 2。一篇 emoji 多的帖子会被算长一截，
 * 而这个数直接决定它进不进「深度好文」—— 于是一篇全是表情的
 * 短帖可能混进长文列表里，正好是这套东西要挡的那种内容。
 */
export function charCountOf(content: string): number {
  return [...content].length;
}
