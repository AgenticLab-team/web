import "server-only";

import { getSettingBool } from "@/lib/settings/store";

/**
 * 论坛对未登录访客开不开。
 *
 * ─────────────────────────────────────────
 * 这个开关在后台摆了很久，而没有任何地方读它
 * ─────────────────────────────────────────
 *
 * `site.forum_public`「论坛允许未登录浏览」一直在设置页上，
 * 管理员关掉它 —— 什么都不会发生，论坛照样对所有人敞着。
 *
 * **一个关不上的开关比没有开关坏得多**：它不是少了个功能，
 * 是给了一个错误的答案。管理员关掉之后不会再去验证，
 * 因为界面已经告诉他关上了。
 *
 * ─────────────────────────────────────────
 * 它管的是「访客」，不是「可见性」
 * ─────────────────────────────────────────
 *
 * 每篇帖子自己的 public / members / group / private 判定原封不动 ——
 * 这个开关只在最外面加一道：**没登录的人还进不进得来**。
 *
 * 两者是与的关系，不是替代关系。开着的时候，访客能看到的
 * 依然只有 public 那一档；关掉的时候，访客一篇都看不到。
 *
 * ─────────────────────────────────────────
 * 榜单不受它管
 * ─────────────────────────────────────────
 *
 * 「未登录访客和其他人还是可以看见大榜单的」是定下来的规矩。
 * 榜单是这个社区对外的门面，论坛是里面的内容 —— 关门不关脸。
 * 所以这个判定只挂在论坛那几条路径上，不做成全站中间件。
 */
export function forumOpenToGuests(): boolean {
  return getSettingBool("site.forum_public", true);
}

/**
 * 这次请求能不能读论坛。
 *
 * 登录用户永远能进（进来之后看得到什么，仍由每篇帖子的可见性决定）。
 */
export function canReadForum(userId: string | null | undefined): boolean {
  return Boolean(userId) || forumOpenToGuests();
}
