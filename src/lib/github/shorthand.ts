import { canonicalUrl, parseShorthand } from "./link-refs";

/**
 * 把正文里的 `owner/repo#123` 变成链接。纯字符串处理，不联网、不查库。
 *
 * ═════════════════════════════════════════
 * 它跑在 markdown 解析**之前**
 * ═════════════════════════════════════════
 *
 * 改的是 markdown 源文，产出的是一条普通的 `[文字](地址)`。
 * 这样做有三个好处，每一个都是「不用再写一遍」：
 *
 *   · 消毒、`target=_blank`、`rel=nofollow` 全都由已有的那条管线管
 *   · 存下来的 HTML 里它就是一条正常的 `<a href="https://github.com/…">`，
 *     于是**「这篇提到的」那套卡片自动就认得它** —— 不用为简写
 *     再造一条从源文捞 ref 的路（造了就是两份，两份迟早对不上）
 *   · 编辑帖子走的是同一个渲染函数，不必单独接
 *
 * 代价是**老帖子不会追溯生效**：正文 HTML 是发表那一刻定下来的。
 * 这是对的 —— 回头改写已经发表的内容，比少几条链接严重得多。
 *
 * ═════════════════════════════════════════
 * 前面那个 lookbehind 是这个文件的全部风险所在
 * ═════════════════════════════════════════
 *
 * `owner/repo#123` 这个形状在别的东西里到处都是：
 *
 *   · `https://github.com/a/b#123`  —— 地址里的一段
 *   · `https://evil.com/a/b#123`    —— **别人域名**里的一段。
 *     认了它就等于把一条指向陌生站点的地址重写成 github.com 上的
 *     另一件东西，而作者写的根本不是那个
 *   · `[看这个](a/b#1)`             —— markdown 链接的目标
 *   · `foo@a/b#1`                   —— 包名、scope
 *
 * 所以前面一个字符必须**不是** 单词字符 / `.` / `/` / `@` / `:` /
 * `-` / `]` / `[` / `(` / `#`。
 *
 * `(` 和 `[` 一起挡掉，意味着 `(owner/repo#1)` 这种英文括号里的
 * 写法认不出来。这是故意的：markdown 链接的目标前面正好是 `(`，
 * 而在那儿动手会把作者写好的链接**改成一段乱码**——
 * 少认一条什么都不会发生，改坏一条是我们弄坏了别人的正文。
 * 中文括号 `（【` 不在 markdown 语法里，所以照常认。
 *
 * 后面不许紧跟单词字符或 `-`（`#12a`、`#12-3` 不认），
 * 也不许紧跟「点 + 数字」（`#1.2` 是版本号，不是编号）；
 * 而 `#123。` `#123，` `#123.` 这种句末照常认 —— 中文正文里
 * 编号后面几乎总是标点。
 */
const SHORTHAND =
  /(?<![\w./@:\-\][(#])([A-Za-z0-9][A-Za-z0-9._-]*)\/([A-Za-z0-9][A-Za-z0-9._-]*)#(\d+)(?![\w-])(?!\.\d)/g;

/**
 * 一段文本里最多改写这么多条。
 *
 * 不是性能考虑 —— 是**版面**：一段把三十个编号连着写下来的话
 * （改动清单、周报），整段会变成一片蓝字，反而没人读得下去。
 * 超过之后后面的原样留着，仍然是作者写的那几个字。
 */
export const MAX_SHORTHAND_LINKS = 12;

export function linkifyGithubShorthand(source: string): string {
  let used = 0;
  return source.replace(SHORTHAND, (match, owner: string, repo: string, digits: string) => {
    if (used >= MAX_SHORTHAND_LINKS) return match;
    const ref = parseShorthand(owner, repo, digits);
    if (!ref) return match;
    used++;
    /*
     * 链接文字**原样是作者写的那串**，不做归一。
     *
     * 显示的和指向的必须是同一件东西：把文字改成规范写法（比如
     * 补全大小写）的话，正文上会出现一个作者没写过的仓库名，
     * 而他自己都认不出那是不是他的意思。
     */
    return `[${match}](${canonicalUrl(ref)})`;
  });
}
